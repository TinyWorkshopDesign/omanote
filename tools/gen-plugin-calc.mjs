#!/usr/bin/env node
// Builds omarchy-plugin/Calc.js from app/src/lib/calc.ts, so the bar plugin computes
// exactly like the app. QML's JavaScript engine lacks a few things calc.ts uses:
//   - Intl.NumberFormat: replaced inside the file by a small formatter that uses the
//     system locale's decimal point and group separator (Qt.locale());
//   - \p{L} / \p{N} in regular expressions (and their `u` flag): replaced by the
//     explicit Basic Multilingual Plane ranges of those Unicode categories;
//   - syntax newer than ES2017 (object spread, `??`, `?.`): lowered by TypeScript.
//
// Usage (from the repository root, after `npm install --prefix app`):
//   node tools/gen-plugin-calc.mjs           write omarchy-plugin/Calc.js
//   node tools/gen-plugin-calc.mjs --check   fail if Calc.js is out of date

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "app", "package.json"));
const ts = require("typescript");

const SRC = path.join(root, "app/src/lib/calc.ts");
const OUT = path.join(root, "omarchy-plugin/Calc.js");

/** The BMP code points matching a Unicode property, as a character-class body. */
function ranges(property) {
  const re = new RegExp(`\\p{${property}}`, "u");
  const hex = (c) => "\\u" + c.toString(16).toUpperCase().padStart(4, "0");
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x10000; c++) {
    const hit = c < 0x10000 && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCharCode(c));
    if (hit && start < 0) start = c;
    if (!hit && start >= 0) {
      out.push(start === c - 1 ? hex(start) : `${hex(start)}-${hex(c - 1)}`);
      start = -1;
    }
  }
  return out.join("");
}

let js = ts.transpileModule(fs.readFileSync(SRC, "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2017, module: ts.ModuleKind.CommonJS, removeComments: true },
}).outputText;

// Regular expression literals using Unicode properties: expand them, drop the `u` flag.
const LETTER = ranges("L");
const NUMBER = ranges("N");
js = js.replace(/\/((?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\\\n[])+)\/([a-z]*)/g, (lit, body, flags) => {
  if (!body.includes("\\p{")) return lit;
  const expanded = body.replaceAll("\\p{L}", LETTER).replaceAll("\\p{N}", NUMBER);
  if (expanded.includes("\\p{")) throw new Error(`unsupported Unicode property in ${lit}`);
  return `/${expanded}/${flags.replace("u", "")}`;
});
if (/\\p\{/.test(js)) throw new Error("a Unicode property escape is left");
// Library methods newer than QML's engine (checked with Quickshell 2026-11): keep calc.ts free of them.
const missing = js.match(/\.(matchAll|flatMap|flat|fromEntries|trimEnd|trimStart|replaceAll|at)\(/);
if (missing) throw new Error(`${missing[1]} is not available in QML's JavaScript engine: avoid it in calc.ts`);

const header = `.pragma library
// GENERATED by tools/gen-plugin-calc.mjs from app/src/lib/calc.ts: do not edit.
// The app's calculator for the Omarchy bar plugin: Calc.evaluate, Calc.formatResult,
// Calc.detectMode, Calc.buildRates, Calc.numbersIn, Calc.countIn.

var Calc = (function () {
  // QML has no Intl: a NumberFormat with the options calc.ts uses
  // (maximumFractionDigits, minimumFractionDigits) and the system locale's separators.
  function NumberFormat(locale, options) {
    var o = options || {};
    var max = o.maximumFractionDigits === undefined ? 3 : o.maximumFractionDigits;
    var min = o.minimumFractionDigits || 0;
    var loc = typeof Qt !== "undefined" && Qt.locale ? Qt.locale() : null;
    var point = loc && loc.decimalPoint ? loc.decimalPoint : ".";
    var group = loc && loc.groupSeparator !== undefined ? loc.groupSeparator : ",";
    this.format = function (value) {
      var v = Number(value);
      if (isNaN(v)) return "NaN";
      if (!isFinite(v)) return v < 0 ? "-∞" : "∞";
      var negative = v < 0;
      v = Math.abs(v);
      // Round on the decimal representation (1.005 -> 1.01), as Intl does.
      var rounded = Number(Math.round(Number(v + "e" + max)) + "e-" + max);
      if (!isFinite(rounded)) rounded = v;
      var parts = rounded.toFixed(max).split(".");
      var int = parts[0];
      var frac = parts[1] || "";
      while (frac.length > min && frac.charAt(frac.length - 1) === "0") frac = frac.slice(0, -1);
      var grouped = int.replace(/\\B(?=(\\d{3})+(?!\\d))/g, group);
      var text = grouped + (frac ? point + frac : "");
      return negative && /[1-9]/.test(text) ? "-" + text : text;
    };
  }
  var Intl = { NumberFormat: NumberFormat };
  var exports = {};

`;

const footer = `
  return exports;
})();
`;

const indented = js.trim().split("\n").map((l) => (l ? "  " + l : l)).join("\n");
const result = header + indented + "\n" + footer;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  // The Unicode ranges follow the Node.js version that wrote the file: compare without them.
  const strip = (t) => t.replace(/\\u[0-9A-F]{4}(?:-\\u[0-9A-F]{4})?/g, "");
  if (strip(current) !== strip(result)) {
    console.error("omarchy-plugin/Calc.js is out of date: run node tools/gen-plugin-calc.mjs");
    process.exit(1);
  }
  console.log("omarchy-plugin/Calc.js is up to date");
} else {
  fs.writeFileSync(OUT, result);
  console.log(`wrote ${path.relative(root, OUT)} (${result.length} bytes)`);
}
