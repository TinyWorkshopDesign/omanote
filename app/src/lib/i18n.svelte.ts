const DICTS: Record<Lang, Dict> = { en, it, es, fr, de, pt, nl, pl };
const STORAGE_KEY = "omanote.lang";

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in LANGUAGES) return saved as Lang;
  } catch {
    /* storage unavailable */
  }
  for (const l of typeof navigator !== "undefined" ? navigator.languages ?? [navigator.language] : []) {
    const code = l.slice(0, 2).toLowerCase();
    if (code in LANGUAGES) return code as Lang;
  }
  return "en";
}

export const i18n = $state({ lang: detect() });

export function setLang(lang: Lang) {
  i18n.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
}

/** Translates a key, filling `{placeholders}`. */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  const s = DICTS[i18n.lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ""));
}

/** Turns a backend error (`CODE` or `CODE|detail`) into a readable message. */
export function errText(e: unknown): string {
  const raw = String(e);
  const [code, ...rest] = raw.split("|");
  const key = `err.${code}` as Key;
  if (key in en) return rest.length ? `${t(key)}: ${rest.join("|")}` : t(key);
  return raw;
}

